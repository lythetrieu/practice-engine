import { defineConfig } from 'astro/config';
import react from '@astrojs/react';
import cloudflare from '@astrojs/cloudflare';
import tailwindcss from '@tailwindcss/vite';
import sitemap from '@astrojs/sitemap';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatProblems, loadPack, packDir } from './src/pack/load.mjs';
import { packPlugin } from './src/pack/vite.mjs';

const ROOT = fileURLToPath(new URL('.', import.meta.url));

// The test pack this build serves: PACK (a pack name under packs/, or a path), set by scripts/pack.mjs from --pack.
const PACK_DIR = packDir(ROOT, process.env.PACK || 'shsat-sample');
const loaded = loadPack(PACK_DIR);
if (!loaded.ok) {
  console.error(`\nThe pack at ${path.relative(ROOT, PACK_DIR)} has problems:\n${formatProblems(loaded.errors)}\n`);
  process.exit(1);
}
const { config } = loaded.pack;

// Canonicals, og:url and the sitemap use the pack's site.url (http://localhost:4321 when it has none).
const SITE = config.site.url || 'http://localhost:4321';

// Kept out of the sitemap: the app, accounts, the API and the admin pages (server-rendered pages are listed unless filtered).
const NOT_IN_SITEMAP = ['/app/', '/account/', '/student/', '/api/', '/admin/', '/404'];

/**
 * Workers static assets answer /about with a 307 to /about/ (html_handling). Rules in _redirects run first,
 * so write a 301 for both URLs of every built page.
 */
const pageRedirects = () => {
  let clientDir;
  return {
    name: 'engine:page-redirects',
    hooks: {
      'astro:config:done': ({ config: c }) => { clientDir = fileURLToPath(c.build.client); },
      'astro:build:done': ({ logger }) => {
        const pages = [];
        const walk = (dir, route) => {
          for (const entry of readdirSync(dir, { withFileTypes: true })) {
            if (!entry.isDirectory() || /^[_.]/.test(entry.name)) continue;
            const sub = path.join(dir, entry.name);
            const url = `${route}/${entry.name}`;
            if (existsSync(path.join(sub, 'index.html')) && !/\s/.test(url)) pages.push(url);
            walk(sub, url);
          }
        };
        walk(clientDir, '');
        const rules = pages.sort().flatMap((p) => [`${p} ${p}/ 301`, `${p}/index.html ${p}/ 301`]);
        const file = path.join(clientDir, '_redirects');
        const head = existsSync(file) ? readFileSync(file, 'utf8').trimEnd() + '\n\n' : '';
        writeFileSync(file, `${head}# Generated by astro.config.mjs: every page without the trailing slash, and its /index.html.\n${rules.join('\n')}\n`);
        logger.info(`_redirects: 301 rules for ${pages.length} pages`);
      },
    },
  };
};

export default defineConfig({
  site: SITE,
  trailingSlash: 'always',
  devToolbar: { enabled: false },
  // no Astro sessions: accounts use their own cookies and D1 (src/lib/server/auth.ts), so no KV namespace is needed
  session: false,
  output: 'static',
  adapter: cloudflare({ imageService: 'compile' }),
  integrations: [
    react(),
    sitemap({
      filter: (url) => {
        const { pathname } = new URL(url);
        return !NOT_IN_SITEMAP.some((p) => pathname.startsWith(p)) && !/\.[a-z0-9]+$/i.test(pathname);
      },
    }),
    pageRedirects(),
  ],
  vite: {
    plugins: [tailwindcss(), packPlugin(PACK_DIR, loaded)],
    // the pack folder lives outside src/: let the dev server read figures and the logo from it
    server: { fs: { allow: [ROOT, PACK_DIR] } },
  },
});
